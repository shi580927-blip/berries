"""Create web copies; preserve original artwork, pixel dimensions and alpha."""
from pathlib import Path
import json,re,hashlib,io
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]
manifest=json.loads((ROOT/'docs/localization_assets_optimized.json').read_text())
localized={a['source'] for a in manifest['assets']}
source=(ROOT/'src/vertical_slice.js').read_text()
paths=set(re.findall(r"I\('[^']+','([^']+)'\)",source))
paths.update('assets/characters/king/king_'+x+'.png' for x in ['idle','point','celebrate','sad'])
paths.update('assets/berries/berry_'+x+'.png' for x in ['strawberry','raspberry','blueberry','gooseberry','blackberry','cloudberry'])
paths.update('assets/ui/icons/ui_'+x+'.png' for x in ['back','coin','settings'])
mapping={};audit=[]
def encode(src,dest):
 im=Image.open(ROOT/src).convert('RGBA');target=ROOT/dest;target.parent.mkdir(parents=True,exist_ok=True)
 encoded=io.BytesIO();im.save(encoded,'WEBP',quality=90,method=4,exact=True,alpha_quality=100)
 temporary=target.with_suffix('.tmp');temporary.write_bytes(encoded.getvalue());temporary.replace(target)
 decoded=Image.open(target).convert('RGBA')
 assert decoded.size==im.size and decoded.getchannel('A').tobytes()==im.getchannel('A').tobytes()
 audit.append(dict(source=src,path=dest,sourceBytes=(ROOT/src).stat().st_size,webBytes=target.stat().st_size))
for src in sorted(paths-localized):
 if not (ROOT/src).is_file():continue
 dest='assets/web/'+src.removeprefix('assets/').rsplit('.',1)[0]+'.webp'
 encode(src,dest);mapping[src]=dest
for a in manifest['assets']:
 for c in a['candidates'].values():
  src=c['path'];dest=src.replace('/optimized/','/web/')
  if not any(row['path']==dest for row in audit):encode(src,dest)
  c['path']=dest;c['sha256']=hashlib.sha256((ROOT/dest).read_bytes()).hexdigest()
(ROOT/'src/optimized-images.js').write_text('// Generated by scripts/optimize_runtime_images.py; originals preserved.\nwindow.__berriesRuntimeImages='+json.dumps(mapping,separators=(',',':'))+';\n')
(ROOT/'docs/localization_assets_web.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2)+'\n')
report=dict(method='WebP quality90, same dimensions, alpha verified exact',files=audit,sourceBytes=sum(x['sourceBytes'] for x in audit),webBytes=sum(x['webBytes'] for x in audit))
(ROOT/'docs/runtime_image_optimization_audit.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({k:v for k,v in report.items() if k!='files'}))
